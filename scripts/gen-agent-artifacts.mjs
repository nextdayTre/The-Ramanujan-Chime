// Deterministic static-artifact generator for the Ramanujan Sphere agent layer.
//
//   node scripts/gen-agent-artifacts.mjs           # (re)write agent/manifest.json + examples
//   node scripts/gen-agent-artifacts.mjs --check   # exit 0 iff committed bytes are current
//
// Reads the ONE shared registry (js/agent-core.js) — nothing is hand-written here, and
// no timestamps/randomness exist, so the output is byte-stable across runs and machines.

import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const AgentCore = require('../js/agent-core.js');

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const AGENT_DIR = join(ROOT, 'agent');
export const EXAMPLES_DIR = join(AGENT_DIR, 'examples');

// One committed success envelope per tool, with documented example inputs.
export const EXAMPLE_DEFINITIONS = {
  manifest: { tool: 'manifest', args: {}, note: 'Envelope whose data is the full capability manifest (read this first without a server).' },
  build_deeplink: { tool: 'build_deeplink', args: { preset: 5, tab: 'harmonics', static: true }, note: 'Canonical link for the Analytic Morlet patch on the harmonics tab.' },
  analyze_patch: { tool: 'analyze_patch', args: { preset: 12 }, note: 'Default Four-Bit Orbit patch: shell metrics, zone histogram, stats, 5 probe points.' },
  eval_point: { tool: 'eval_point', args: { preset: 12, t: 0.25 }, note: 'Playhead point at t=0.25 with float32 bits, twins and telemetry.' },
  bit_inspect: { tool: 'bit_inspect', args: { value: 3.141592653589793 }, note: 'π as float32: hex 0x40490FDB.' },
  discrete_group: { tool: 'discrete_group', args: { orderN: 12, stride: 3 }, note: 'Composite N=12, stride 3: gcd 3, 4-state subgroup.' },
  ramanujan_pi: { tool: 'ramanujan_pi', args: { maxK: 2 }, note: 'Ramanujan 1/π vs Fourier odd harmonics convergence.' },
  fourbit_orbit: { tool: 'fourbit_orbit', args: { R: 1, playT: 0.25 }, note: 'θ=90°: 1111/F apex, 8↔1 equatorial pair, Quadray tetrahedron.' },
  frobenius_secp: { tool: 'frobenius_secp', args: { k: 4 }, note: 'secp256k1 Frobenius trace S_4 and exact point count #E(F_p^4).' }
};

function serialize(value) {
  return JSON.stringify(value, null, 2) + '\n';
}

// Pure: returns Map<absolutePath, fileContents> without touching disk.
export function artifactContents() {
  const files = new Map();
  files.set(join(AGENT_DIR, 'manifest.json'), serialize(AgentCore.getManifest()));

  const index = [];
  for (const [fileName, def] of Object.entries(EXAMPLE_DEFINITIONS)) {
    const envelope = AgentCore.callTool(def.tool, def.args);
    if (!envelope || envelope.ok !== true) {
      const detail = envelope && envelope.error ? `${envelope.error.code}: ${envelope.error.message}` : 'no envelope';
      throw new Error(`example ${fileName} failed: ${detail}`);
    }
    files.set(join(EXAMPLES_DIR, `${fileName}.json`), serialize(envelope));
    const argsText = Object.keys(def.args).length ? '`' + JSON.stringify(def.args) + '`' : '`{}`';
    index.push(`- \`${fileName}.json\` — tool \`${def.tool}\`, args ${argsText} — ${def.note}`);
  }
  files.set(
    join(EXAMPLES_DIR, 'README.md'),
    [
      '# Generated agent examples',
      '',
      'One committed success envelope per tool, generated by',
      '`node scripts/gen-agent-artifacts.mjs` from the shared registry',
      '(`js/agent-core.js`). Do not hand-edit; verify with `--check`.',
      '',
      'Each file is `{ ok, schemaVersion, tool, data, deeplink, warnings }`',
      'exactly as the CLI `--json` output and the MCP `tools/call` text content.',
      '',
      ...index,
      ''
    ].join('\n')
  );
  return files;
}

export function buildArtifacts() {
  const files = artifactContents();
  mkdirSync(EXAMPLES_DIR, { recursive: true });
  for (const [path, content] of files) writeFileSync(path, content);
  return files;
}

export function checkArtifacts() {
  const files = artifactContents();
  let stale = 0;
  for (const [path, content] of files) {
    if (!existsSync(path)) {
      console.error(`missing agent artifact: ${path}`);
      stale += 1;
      continue;
    }
    if (readFileSync(path, 'utf8') !== content) {
      console.error(`stale agent artifact: ${path}`);
      stale += 1;
    }
  }
  return stale;
}

export function main(argv = process.argv.slice(2)) {
  if (argv.includes('--check')) {
    const stale = checkArtifacts();
    if (stale > 0) {
      console.error('run: node scripts/gen-agent-artifacts.mjs');
      return 1;
    }
    console.log(`agent artifacts up to date: ${artifactContents().size} file(s)`);
    return 0;
  }
  const count = buildArtifacts().size;
  console.log(`agent artifacts written: ${count} file(s)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main());
}
